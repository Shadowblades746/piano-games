export default function createNoteFlashcards(ctx) {
  const { scope, storage: prefs } = ctx;

  const state = {
    level: 'pentascale',
    countMode: '5',
    displayMode: 'both',
    midiPlayMode: 'answer',
    currentSequence: [],
    userTypedLetters: [],
    isRevealed: false,
    madeMistake: false,
    autoAdvanceTimer: null,
  };

  let root = null;
  let $ = () => null;
  let keyboard = null;
  let staff = null;
  let listener = null;
  let sequenceHandle = null;
  let resizeTimer = null;

  const isDone = (idx) => state.isRevealed || idx < state.userTypedLetters.length;

  // ==========================================
  // Rendering
  // ==========================================
  function renderPiano() {
    const lvl = FLASHCARD_LEVELS[state.level];
    keyboard.setRanges(lvl.pianoRangeDesktop, lvl.pianoRangeMobile);
    keyboard.render();
    $('pianoRangeLabel').textContent = keyboard.rangeLabel;
    updatePianoCounters();
  }

  function updatePianoCounters() {
    if (state.displayMode === 'staff' && !state.isRevealed) { keyboard.setCounters([]); return; }
    keyboard.setCounters(state.currentSequence.map((note, seqIdx) => {
      const done = isDone(seqIdx);
      const duplicate = state.currentSequence.filter((n) => n.id === note.id).length > 1;
      return { seqIdx, noteId: note.id, done, text: done ? note.letter : (duplicate ? String(seqIdx + 1) : '') };
    }));
  }

  function renderStaff() {
    staff.render({
      clef: FLASHCARD_LEVELS[state.level].clef,
      notes: state.currentSequence,
      mobile: isMobileViewport(),
      isDone,
      hint: state.displayMode === 'piano' && !state.isRevealed ? 'Look at the blue dots on the piano keys above!' : null,
      onNoteClick: (idx, note) => {
        audio.playTone(note.freq, { duration: 0.65 });
        highlightDot(idx, true);
        keyboard.pressNote(note.id, true);
        scope.timeout(() => { highlightDot(idx, false); keyboard.pressNote(note.id, false); }, 350);
      },
    });
  }

  function highlightDot(idx, active) {
    keyboard.flagCounter(idx, 'active-play', active);
    if (active) staff.setState(idx, 'gold'); else staff.refresh(idx);
  }

  function flashWrong(idx, wrongNoteId = null) {
    keyboard.flagCounter(idx, 'wrong-flash', true);
    staff.setState(idx, 'red');
    if (wrongNoteId) keyboard.markWrong(wrongNoteId, true);
    scope.timeout(() => {
      keyboard.flagCounter(idx, 'wrong-flash', false);
      staff.refresh(idx);
      if (wrongNoteId) keyboard.markWrong(wrongNoteId, false);
    }, 340);
  }

  function updateHeardDisplay(wrongLetter = null) {
    const display = $('heardLettersDisplay');
    const matched = state.userTypedLetters.join(' · ');
    if (wrongLetter) {
      display.innerHTML = `${matched ? matched + ' · ' : ''}<span class="text-rose-400 line-through">${escapeHtml(wrongLetter)}</span>`;
    } else {
      display.textContent = matched;
    }
  }

  // ==========================================
  // Audio helpers
  // ==========================================
  function playSequenceAudio() {
    if (sequenceHandle) sequenceHandle.cancel();
    keyboard.clearPressed();
    sequenceHandle = audio.playSequence(state.currentSequence, {
      gap: 420, duration: 0.65, noteLength: 350,
      onStep: (i, note) => { highlightDot(i, true); keyboard.pressNote(note.id, true); },
      onStepEnd: (i, note) => { highlightDot(i, false); keyboard.pressNote(note.id, false); },
    });
  }

  /** The note a typed/tapped letter should sound like for the current level. */
  function playLetterTone(letter) {
    const expected = state.currentSequence[state.userTypedLetters.length];
    let note = (expected && !state.isRevealed && expected.letter === letter) ? expected : null;
    if (!note) {
      const anchor = getNote(FLASHCARD_LEVELS[state.level].noteIds[0]).midi;
      note = ALL_NOTES.filter((n) => n.letter === letter)
        .sort((a, b) => Math.abs(a.midi - anchor) - Math.abs(b.midi - anchor))[0];
    }
    if (note) audio.playTone(note.freq, { duration: 0.45 });
  }

  // ==========================================
  // Game flow
  // ==========================================
  function generateChallenge(forceAscendingFirst = false) {
    scope.clear(state.autoAdvanceTimer);
    if (sequenceHandle) sequenceHandle.cancel();
    state.isRevealed = false;
    state.madeMistake = false;
    state.userTypedLetters = [];
    updateHeardDisplay();

    const pool = FLASHCARD_LEVELS[state.level].noteIds.map(getNote);
    const numDots = state.countMode === 'random' ? pickRandom([1, 2, 3, 4, 5]) : parseInt(state.countMode, 10);

    const sequence = [];
    if (forceAscendingFirst && state.level === 'pentascale' && numDots === 5) {
      sequence.push(...pool.slice(0, 5));
    } else if (numDots === 1) {
      let candidate = pickRandom(pool);
      if (state.currentSequence.length === 1 && pool.length > 1) {
        while (candidate.id === state.currentSequence[0].id) candidate = pickRandom(pool);
      }
      sequence.push(candidate);
    } else {
      let idx = Math.floor(Math.random() * pool.length);
      sequence.push(pool[idx]);
      for (let i = 1; i < numDots; i++) {
        const delta = pickRandom([-2, -1, -1, 1, 1, 2]);
        let next = idx + delta;
        if (next < 0 || next >= pool.length) next = idx - delta;
        idx = Math.max(0, Math.min(pool.length - 1, next));
        sequence.push(pool[idx]);
      }
    }
    state.currentSequence = sequence;

    const badge = $('challengeBadge');
    badge.className = BADGE_PROMPT;
    badge.textContent = numDots === 1 ? 'Say the note name out loud' : `Say the ${numDots} notes left to right`;

    const midiAnswerMode = midi.connected && state.midiPlayMode === 'answer';
    $('answerBanner').innerHTML = `
      <p class="text-[#5c4332] text-xs sm:text-sm text-center">
        ${midiAnswerMode
          ? `Say &amp; play on <strong class="text-[#2c1e16] font-semibold">${escapeHtml(midi.deviceName || 'your MIDI piano')}</strong>`
          : `Read the blue ${numDots === 1 ? 'dot' : 'dots'} out loud, then tap <strong class="text-[#2c1e16] font-semibold">Reveal &amp; Hear</strong>`}
      </p>`;

    renderPiano();
    renderStaff();
  }

  /** solved = completed by answering (counts toward the streak if no mistakes). */
  function revealAnswer({ playAudio = true, solved = false } = {}) {
    if (!state.isRevealed) {
      state.isRevealed = true;
      ctx.score.award(1);
      if (solved && !state.madeMistake) ctx.score.hit(); else ctx.score.miss();
    }
    const badge = $('challengeBadge');
    badge.className = BADGE_DONE;
    badge.textContent = '✓ Answer Revealed';

    $('answerBanner').innerHTML = `<div class="flex flex-wrap items-center justify-center gap-1 sm:gap-1.5">${
      state.currentSequence.map((note, idx) => `
        <span class="inline-flex items-center justify-center w-7 h-7 sm:w-8 sm:h-8 rounded-full bg-emerald-600 text-white font-display font-bold text-sm sm:text-base shadow-sm border border-emerald-300">${note.letter}</span>
        ${idx < state.currentSequence.length - 1 ? '<span class="text-[#9e856d] font-semibold">–</span>' : ''}`).join('')
    }</div>`;

    updatePianoCounters();
    renderStaff();
    if (playAudio) playSequenceAudio();
  }

  function handleLetterInput(letter, { fromMidi = false, midiNoteObj = null, rawMidiNumber = null } = {}) {
    if (state.isRevealed) return;
    const stepIdx = state.userTypedLetters.length;
    const expected = state.currentSequence[stepIdx];
    if (!expected) return;

    const isMatch = fromMidi && rawMidiNumber !== null
      ? (rawMidiNumber === expected.midi || pitchClassName(rawMidiNumber) === expected.letter)
      : letter === expected.letter;
    appStorage.recordNote(expected.id, isMatch);

    if (!isMatch) {
      state.madeMistake = true;
      ctx.score.miss();
      updateHeardDisplay(letter);
      flashWrong(stepIdx, fromMidi && midiNoteObj ? midiNoteObj.id : null);
      if (fromMidi) audio.playThud();
      return;
    }

    state.userTypedLetters.push(expected.letter);
    updateHeardDisplay();
    updatePianoCounters();
    renderStaff();
    highlightDot(stepIdx, true);
    scope.timeout(() => highlightDot(stepIdx, false), 260);

    if (state.userTypedLetters.length === state.currentSequence.length) {
      const letters = state.currentSequence.map((n) => n.letter).join(' - ');
      if (fromMidi) {
        revealAnswer({ playAudio: false, solved: true });
        showToast(`✓ Nailed ${letters}!`);
        state.autoAdvanceTimer = scope.timeout(() => generateChallenge(false), 650);
      } else {
        showToast(`Awesome! You got ${letters}!`);
        revealAnswer({ playAudio: true, solved: true });
      }
    }
  }

  // ==========================================
  // Mic / MIDI / mute UI
  // ==========================================
  function setMicUI(on) {
    const btn = $('micBtn');
    btn.classList.toggle('mic-pulse', on);
    ['bg-red-100', 'text-red-700', 'border-red-300'].forEach((c) => btn.classList.toggle(c, on));
    ['bg-[#fcf8ee]', 'text-[#3d2a1f]', 'border-[#cbb894]'].forEach((c) => btn.classList.toggle(c, !on));
    $('micLabel').textContent = on ? 'Listening' : 'Mic Off';
    $('voiceFeedbackBar').classList.toggle('hidden', !on);
  }

  function toggleListening() {
    if (!listener.supported) {
      showToast('Auto-Listen mic is unavailable on this mobile browser—just say letters out loud and tap Reveal & Hear!');
      return;
    }
    if (listener.listening) { listener.stop(); return; }
    const res = listener.start();
    showToast(res.ok ? 'Mic on! Say the note letters out loud.' : 'Could not start the microphone. Try again.');
  }

  function updateMidiModeUI() {
    const btn = $('midiModeToggleBtn');
    btn.classList.toggle('hidden', !midi.connected);
    btn.classList.toggle('inline-flex', midi.connected);

    const answer = state.midiPlayMode === 'answer';
    $('midiModeIcon').textContent = answer ? '🎯' : '🎹';
    $('midiModeLabel').textContent = answer ? 'Play-to-Answer' : 'Free Play';
    ['bg-emerald-100', 'text-emerald-900', 'border-emerald-300'].forEach((c) => btn.classList.toggle(c, answer));
    ['bg-sky-100', 'text-sky-900', 'border-sky-300'].forEach((c) => btn.classList.toggle(c, !answer));
  }

  function toggleMidiPlayMode() {
    state.midiPlayMode = state.midiPlayMode === 'answer' ? 'free' : 'answer';
    prefs.set('midiPlayMode', state.midiPlayMode);
    updateMidiModeUI();
    showToast(state.midiPlayMode === 'free'
      ? 'Free Play mode: Keys light up on screen without advancing flashcards.'
      : 'Play-to-Answer mode: Play each dot left-to-right to solve & auto-advance.');
  }

  function updateMuteUI(muted) {
    const btn = $('synthMuteBtn');
    $('synthMuteIcon').textContent = muted ? '🔇' : '🔊';
    $('synthMuteLabel').textContent = muted ? 'Muted' : 'Audio';
    ['text-[#3d2a1f]', 'bg-[#fcf8ee]', 'border-[#cbb894]'].forEach((c) => btn.classList.toggle(c, !muted));
    ['text-amber-900', 'border-amber-400', 'bg-amber-100'].forEach((c) => btn.classList.toggle(c, muted));
  }

  // ==========================================
  // Lifecycle
  // ==========================================
  function mount(rootEl) {
    root = rootEl;
    root.innerHTML = TEMPLATE;
    $ = (id) => root.querySelector(`#${id}`);

    // Restore preferences
    const savedLevel = prefs.get('level');
    if (FLASHCARD_LEVELS[savedLevel]) state.level = savedLevel;
    const savedCount = prefs.get('countMode');
    if (['1', '3', '5', 'random'].includes(savedCount)) state.countMode = savedCount;
    const savedDisplay = prefs.get('displayMode');
    if (['both', 'staff', 'piano'].includes(savedDisplay)) state.displayMode = savedDisplay;
    if (prefs.get('midiPlayMode') === 'free') state.midiPlayMode = 'free';
    $('levelSelect').value = state.level;
    $('countSelect').value = state.countMode;
    $('displayModeSelect').value = state.displayMode;

    keyboard = createKeyboard($('pianoContainer'), {
      onKeyPress: (note) => { audio.playTone(note.freq, { duration: 0.6 }); handleLetterInput(note.letter); },
      onBlackKeyPress: ({ freq }) => audio.playTone(freq, { duration: 0.5 }),
    });
    staff = createCounterStaff($('staffSvg'));
    listener = createLetterListener({
      onLetter: (letter) => handleLetterInput(letter),
      onStart: () => setMicUI(true),
      onStop: () => setMicUI(false),
      onError: (code) => showToast(code === 'not-allowed' || code === 'service-not-allowed'
        ? 'Mic permission blocked. Allow microphone access, or say the letters out loud and tap Reveal & Hear!'
        : 'Voice recognition is unavailable right now. Say the letters out loud and tap Reveal & Hear!'),
    });

    // Header: filters toggle
    const filterBtn = ctx.addHeaderButton({
      icon: FILTER_ICON, label: 'Filters', title: 'Toggle practice filters',
      onClick: () => {
        const hidden = $('filterBar').classList.toggle('hidden');
        filterBtn.setAttribute('aria-expanded', String(!hidden));
      },
    });
    filterBtn.setAttribute('aria-expanded', 'true');

    // Filters
    scope.listen($('levelSelect'), 'change', (e) => {
      state.level = e.target.value; prefs.set('level', state.level);
      e.target.blur(); generateChallenge(false);
    });
    scope.listen($('countSelect'), 'change', (e) => {
      state.countMode = e.target.value; prefs.set('countMode', state.countMode);
      e.target.blur(); generateChallenge(false);
    });
    scope.listen($('displayModeSelect'), 'change', (e) => {
      state.displayMode = e.target.value; prefs.set('displayMode', state.displayMode);
      e.target.blur(); renderPiano(); renderStaff();
    });

    // Controls
    scope.listen($('revealBtn'), 'click', () => revealAnswer());
    scope.listen($('nextBtn'), 'click', () => generateChallenge(false));
    scope.listen($('playSoundBtn'), 'click', playSequenceAudio);
    scope.listen($('micBtn'), 'click', toggleListening);
    scope.listen($('synthMuteBtn'), 'click', () => {
      showToast(audio.toggleMute()
        ? 'Browser audio muted (ideal for P-125 speakers or Pianoteq).'
        : 'Browser piano audio enabled.');
    });
    scope.listen($('midiModeToggleBtn'), 'click', toggleMidiPlayMode);
    scope.listen($('clearHeardBtn'), 'click', () => {
      state.userTypedLetters = [];
      updateHeardDisplay(); updatePianoCounters(); renderStaff();
    });
    root.querySelectorAll('.letter-btn').forEach((btn) => {
      scope.listen(btn, 'click', () => { playLetterTone(btn.dataset.letter); handleLetterInput(btn.dataset.letter); });
    });

    scope.listen(window, 'resize', () => {
      scope.clear(resizeTimer);
      resizeTimer = scope.timeout(() => { renderPiano(); renderStaff(); }, 150);
    });

    // Shared services
    scope.add(audio.onMuteChange(updateMuteUI));
    updateMuteUI(audio.isMuted());
    scope.add(midi.on('noteon', ({ note }) => {
      keyboard.pressMidi(note, true);
      if (state.midiPlayMode === 'answer') {
        handleLetterInput(pitchClassName(note), { fromMidi: true, midiNoteObj: noteForMidi(note), rawMidiNumber: note });
      }
    }));
    scope.add(midi.on('noteoff', ({ note }) => keyboard.pressMidi(note, false)));
    scope.add(midi.on('status', ({ event }) => {
      updateMidiModeUI();
      if (event === 'connected') generateChallenge(false);
    }));

    updateMidiModeUI();
    generateChallenge(true);
  }

  function unmount() {
    if (listener) listener.destroy();
    if (sequenceHandle) sequenceHandle.cancel();
    if (keyboard) keyboard.destroy();
    if (root) root.innerHTML = '';
    listener = keyboard = staff = sequenceHandle = null;
  }

  /** Called by the shell for every keydown (modifiers / form fields / repeats already filtered). */
  function onKeyDown(e) {
    const onButton = e.target.tagName === 'BUTTON';
    if (/^[a-gA-G]$/.test(e.key)) {
      const letter = e.key.toUpperCase();
      playLetterTone(letter);
      handleLetterInput(letter);
    } else if (e.code === 'ArrowRight') {
      e.preventDefault(); generateChallenge(false);
    } else if (!onButton && e.code === 'Space') {
      e.preventDefault();
      if (!state.isRevealed) revealAnswer(); else playSequenceAudio();
    } else if (!onButton && e.code === 'Enter') {
      e.preventDefault(); generateChallenge(false);
    }
  }

  return { mount, unmount, onKeyDown };
}
