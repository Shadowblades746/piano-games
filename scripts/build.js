/**
 * Zero-dependency build script that bundles NoteReader modules into dist/app.bundle.js
 * Enables NoteReader to run seamlessly both:
 *  - via double-click on file:/// (where browsers block raw ES module imports via CORS)
 *  - on static hosts like Vercel and GitHub Pages
 */

const fs = require('fs');
const path = require('path');

const srcDir = path.resolve(__dirname, '../src');
const distDir = path.resolve(__dirname, '../dist');

if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
}

const files = [
    'src/core/notes.js',
    'src/core/audio.js',
    'src/core/midi.js',
    'src/core/speech.js',
    'src/core/storage.js',
    'src/ui/staff.js',
    'src/ui/keyboard.js',
    'src/ui/toast.js',
    'src/games/note-flashcards.js',
    'src/games/listen-match.js',
    'src/games/registry.js',
    'src/main.js'
];

function transformModule(code) {
    let out = code;
    const exportsToAppend = [];

    // import { a, b as c } from 'path';
    out = out.replace(/import\s*\{\s*([^}]+)\s*\}\s*from\s*['"]([^'"]+)['"];?/g, (m, names, p) => {
        return `const { ${names} } = _require('${p}');`;
    });

    // import defaultName from 'path';
    out = out.replace(/import\s*([a-zA-Z0-9_$]+)\s*from\s*['"]([^'"]+)['"];?/g, (m, name, p) => {
        return `const ${name} = _requireDefault('${p}');`;
    });

    // export default ...
    out = out.replace(/export\s+default\s+/g, 'module.exports.default = ');

    // export const / let / var name = ...
    out = out.replace(/export\s+(const|let|var)\s+([a-zA-Z0-9_$]+)\s*=/g, (m, type, name) => {
        exportsToAppend.push(name);
        return `${type} ${name} =`;
    });

    // export function name(...)
    out = out.replace(/export\s+function\s+([a-zA-Z0-9_$]+)\s*\(/g, (m, name) => {
        exportsToAppend.push(name);
        return `function ${name}(`;
    });

    // export class name
    out = out.replace(/export\s+class\s+([a-zA-Z0-9_$]+)/g, (m, name) => {
        exportsToAppend.push(name);
        return `class ${name}`;
    });

    // export { a, b as c };
    out = out.replace(/export\s*\{\s*([^}]+)\s*\};?/g, (m, names) => {
        return names.split(',').filter(Boolean).map(n => {
            const parts = n.trim().split(/\s+as\s+/);
            const orig = parts[0].trim();
            const alias = (parts[1] || parts[0]).trim();
            return `module.exports.${alias} = ${orig};`;
        }).join('\n');
    });

    if (exportsToAppend.length > 0) {
        out += '\n' + exportsToAppend.map(name => `module.exports.${name} = ${name};`).join('\n');
    }

    return out;
}

const moduleEntries = [];

files.forEach(fileKey => {
    const filePath = path.resolve(__dirname, '..', fileKey);
    const raw = fs.readFileSync(filePath, 'utf8');
    const transformed = transformModule(raw);

    const normalizedKey = fileKey.replace(/\\/g, '/');
    moduleEntries.push(`
    // ==========================================
    // MODULE: ${normalizedKey}
    // ==========================================
    modules['${normalizedKey}'] = function(module, exports, _require, _requireDefault) {
${transformed}
    };`);
});

const bundleCode = `/**
 * NoteReader — Self-Contained Application Bundle
 * Generated by scripts/build.js
 * Enables NoteReader to run in any browser via file:/// as well as http(s)://
 */
(function() {
    'use strict';
    const modules = {};
    const cache = {};

    function normalizePath(base, rel) {
        if (!rel.startsWith('.')) return rel;
        const stack = base.split('/').slice(0, -1);
        const parts = rel.split('/');
        for (const part of parts) {
            if (part === '.' || part === '') continue;
            if (part === '..') stack.pop();
            else stack.push(part);
        }
        return stack.join('/');
    }

    function _requireModule(id) {
        if (cache[id]) return cache[id].exports;
        const fn = modules[id];
        if (!fn) throw new Error('Module not found: ' + id);

        const mod = { exports: {} };
        cache[id] = mod;

        const localRequire = function(relPath) {
            const resolved = normalizePath(id, relPath);
            return _requireModule(resolved);
        };

        const localRequireDefault = function(relPath) {
            const res = localRequire(relPath);
            return (res && typeof res === 'object' && 'default' in res) ? res.default : res;
        };

        fn(mod, mod.exports, localRequire, localRequireDefault);
        return mod.exports;
    }

${moduleEntries.join('\n')}

    // Initialize application entrypoint
    _requireModule('src/main.js');
})();
`;

fs.writeFileSync(path.resolve(distDir, 'app.bundle.js'), bundleCode, 'utf8');
console.log('Successfully bundled to dist/app.bundle.js (' + bundleCode.length + ' bytes)');
